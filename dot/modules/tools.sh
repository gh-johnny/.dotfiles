# shellcheck shell=bash
# User-space tools, the part that is the same on every distro:
#   mise        runtimes from the stowed ~/.config/mise/config.toml, plus the tools the repos of
#               this distro lack (written to ~/.config/mise/conf.d/dot.toml, generated, not stowed)
#   npm         global npm packages (manifest/npm.list) on mise's node
#   uv          Python CLI tools (manifest/uv.list)
#   installers  vendor install scripts (manifest/installers.list)

DOT_MISE_CONF=${XDG_CONFIG_HOME:-$HOME/.config}/mise/conf.d/dot.toml

# ── installers (used by the others to bootstrap mise and uv) ─────────────────

# installer_run NAME: run installers.list's script for NAME unless its check command exists.
installer_run() {
  local line check shell url f
  line=$(installer_line "$1") || { err "no installer named $1"; return 1; }
  read -r check shell url <<<"$line"
  installer_present "$check" && return 0
  local host=${url#*://}; host=${host%%/*}
  online "$host" || { warn "$1: $host is unreachable, skipping"; return 1; }
  info "installing $1 ($url)"
  f="$DOT_RUN/installer-$1"
  fetch "$url" >"$f" || { err "$1: download failed"; return 1; }
  run "$shell" "$f" || { err "$1: installer failed"; return 1; }
  hash -r
}

# installer_present CHECK: a command name, or a path (~ allowed) that must exist.
installer_present() {
  local c=$1
  if [[ $c == */* ]]; then c=${c/#\~/$HOME}; [[ -e $c ]]; else has "$c"; fi
}

mod_installers_apply() {
  system_plan
  local name check shell url logical rc=0 n=0
  while read -r name check shell url; do
    installer_present "$check" && continue
    n=$((n + 1)); installer_run "$name" || rc=1
  done < <(list_lines installers.list)
  while IFS=$'\t' read -r logical name; do
    n=$((n + 1)); installer_run "$name" || rc=1
  done <"$DOT_RUN/plan-script"
  ((n)) || ok "installers: everything present"
  return $rc
}

mod_installers_status() {
  system_plan
  local name check shell url logical
  while read -r name check shell url; do
    if installer_present "$check"; then report ok "$name"; else report miss "$name ($url)"; fi
  done < <(list_lines installers.list)
  while IFS=$'\t' read -r logical name; do report miss "$logical (installer $name)"; done <"$DOT_RUN/plan-script"
}

# ── mise ─────────────────────────────────────────────────────────────────────

_mise_wanted() { system_plan; cut -f2 "$DOT_RUN/plan-mise" | sort -u; }

_mise_conf() {
  local t wanted
  wanted=$(_mise_wanted)
  [[ -n $wanted || $OS_LIBC == musl ]] || return 0
  echo '# Generated by `dot apply` (dot/modules/tools.sh). Not stowed, not committed:'
  echo '# edit dot/manifest/packages.list instead.'
  if [[ $OS_LIBC == musl ]]; then
    # nodejs.org has no musl binaries; without this mise compiles node from source
    echo '[settings]'
    echo 'node.flavor = "musl"'
    echo 'node.mirror_url = "https://unofficial-builds.nodejs.org/download/release/"'
  fi
  [[ -n $wanted ]] || return 0
  echo '[tools]'
  while read -r t; do [[ -n $t ]] && printf '"%s" = "latest"\n' "$t"; done <<<"$wanted"
}

mise_ensure() {
  has mise && return 0
  if [[ -z $(pkg_missing mise) ]] || { pkg_available mise && pkg_install mise; }; then hash -r; has mise && return 0; fi
  installer_run mise && hash -r && has mise
}

mod_mise_apply() {
  local wanted conf=${XDG_CONFIG_HOME:-$HOME/.config}/mise/config.toml
  wanted=$(_mise_wanted)
  if [[ -z $wanted && ! -e $conf ]]; then ok "mise: nothing to do"; return 0; fi
  mise_ensure || { err "mise is not installed and could not be"; return 1; }
  local new
  new=$(_mise_conf)
  if [[ -n $new ]]; then
    if [[ ! -f $DOT_MISE_CONF || $(<"$DOT_MISE_CONF") != "$new" ]]; then
      run mkdir -p "${DOT_MISE_CONF%/*}"
      if [[ $DOT_DRY != 1 ]]; then printf '%s\n' "$new" >"$DOT_MISE_CONF"; fi
      echo "write $DOT_MISE_CONF" >>"$DOT_RUN/changes"
      [[ -n $wanted ]] && info "mise: $(tr '\n' ' ' <<<"$wanted")"
    fi
  elif [[ -f $DOT_MISE_CONF ]]; then
    run rm -f "$DOT_MISE_CONF"
  fi
  local missing
  missing=$(cd "$HOME" && mise ls --missing 2>/dev/null | awk '{print $1"@"$2}')
  if [[ -z $missing ]]; then ok "mise: all tools installed"; return 0; fi
  info "mise: installing $(tr '\n' ' ' <<<"$missing")"
  (cd "$HOME" && { run mise install --yes || { warn "mise install failed, retrying once"; run mise install --yes; }; }) || { err "mise install failed (offline? GitHub rate limit? set GITHUB_TOKEN)"; return 1; }
}

mod_mise_status() {
  if ! has mise; then
    [[ -n $(_mise_wanted) ]] && report miss "mise (needed for: $(_mise_wanted | tr '\n' ' '))" || report skip "mise not installed"
    return 0
  fi
  local line
  while read -r line; do
    [[ -n $line ]] && report miss "mise: $line"
  done < <(cd "$HOME" && mise ls --missing 2>/dev/null | awk '{print $1"@"$2}')
  report ok "mise $(mise --version 2>/dev/null | awk '{print $1}'): $(cd "$HOME" && mise ls --installed 2>/dev/null | awk '{print $1}' | sort -u | tr '\n' ' ')"
}

# ── npm ──────────────────────────────────────────────────────────────────────

_npm() { if has mise; then (cd "$HOME" && mise exec -- npm "$@"); else npm "$@"; fi; }
_npm_ok() { { has mise && (cd "$HOME" && mise which npm >/dev/null 2>&1); } || has npm; }
_npm_global() { _npm ls -g --depth=0 --parseable 2>/dev/null | sed -E 's|.*/node_modules/||' | sort -u; }

mod_npm_apply() {
  local want=() p have
  mapfile -t want < <(list_lines npm.list | awk 'NF {print $1}')
  ((${#want[@]})) || return 0
  _npm_ok || { warn "npm: no node (mise should provide it), skipping ${want[*]}"; return 1; }
  have=$(_npm_global)
  local missing=()
  for p in "${want[@]}"; do grep -qxF "$p" <<<"$have" || missing+=("$p"); done
  ((${#missing[@]})) || { ok "npm: global packages installed"; return 0; }
  info "npm: installing ${missing[*]}"
  if has mise; then (cd "$HOME" && run mise exec -- npm install -g --silent "${missing[@]}")
  else run npm install -g --silent "${missing[@]}"
  fi
}

mod_npm_status() {
  local p have
  [[ -n $(list_lines npm.list) ]] || return 0
  _npm_ok || { report miss "npm (no node)"; return 0; }
  have=$(_npm_global)
  for p in $(list_lines npm.list | awk 'NF {print $1}'); do
    if grep -qxF "$p" <<<"$have"; then report ok "npm $p"; else report miss "npm $p"; fi
  done
}

# ── uv ───────────────────────────────────────────────────────────────────────

_uv_tools() { uv tool list 2>/dev/null | awk '/^[^-[:space:]]/ {print $1}'; }

mod_uv_apply() {
  local name spec have rc=0
  [[ -n $(list_lines uv.list) ]] || return 0
  if ! has uv; then
    { pkg_available uv && pkg_install uv && hash -r; } || installer_run uv || true
    hash -r
    has uv || { err "uv is not installed and could not be"; return 1; }
  fi
  have=$(_uv_tools)
  local n=0
  while read -r name spec; do
    grep -qxF "$name" <<<"$have" && continue
    n=$((n + 1))
    run uv tool install --quiet "${spec:-$name}" || rc=1
  done < <(list_lines uv.list)
  ((n)) || ok "uv: tools installed"
  return $rc
}

mod_uv_status() {
  local name spec have
  [[ -n $(list_lines uv.list) ]] || return 0
  has uv || { report miss "uv"; return 0; }
  have=$(_uv_tools)
  while read -r name spec; do
    if grep -qxF "$name" <<<"$have"; then report ok "uv $name"; else report miss "uv $name (${spec:-$name})"; fi
  done < <(list_lines uv.list)
}
